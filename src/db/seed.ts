function computeOrderTotals(parts: WorkOrderPart[], labor: WorkOrderLabor[], ivaRate: number) {
  const partsTotal = parts.reduce((acc, p) => acc + p.totalPrice, 0);
  const laborTotal = labor.reduce((acc, l) => acc + l.totalPrice, 0);
  const cmvTotal = parts.reduce((acc, p) => acc + p.unitCost * p.quantity, 0);
  const subtotal = partsTotal + laborTotal;
  const ivaAmount = Math.round(subtotal * (ivaRate / 100));
  const total = subtotal + ivaAmount;
  return {subtotal, ivaAmount, total, cmvTotal};
}

