export async function ensureDatabaseSeeded(): Promise<void> {
  const existingOrders = await db.workOrders.count();
  const existingSettings = await db.workshopSettings.toCollection().first();
  const defaultHash = await hashPassword(INITIAL_WORKSHOP_PASSWORD);

  if (existingOrders > 0 && existingSettings) {
    // Backfill passwordHash on existing local users created prior to credential enforcement
    const usersWithoutHash = await db.workshopUsers.filter((u) => !u.passwordHash).toArray();
    if (usersWithoutHash.length > 0) {
      await db.workshopUsers.bulkPut(
        usersWithoutHash.map((u) => ({...u, passwordHash: defaultHash}))
      );
    }
    return;
  }

  await db.transaction(
    'rw',
    [
      db.workshopSettings,
      db.clients,
      db.vehicles,
      db.suppliers,
      db.stockItems,
      db.stockMovements,
      db.workOrders,
      db.paymentRecords,
      db.workshopUsers,
    ],
    async () => {
      if (!existingSettings) {
        await db.workshopSettings.put(DEFAULT_SETTINGS);
      }
      if ((await db.clients.count()) === 0) {
        await db.clients.bulkPut(SEED_CLIENTS);
      }
      if ((await db.vehicles.count()) === 0) {
        await db.vehicles.bulkPut(SEED_VEHICLES);
      }
      if ((await db.suppliers.count()) === 0) {
        await db.suppliers.bulkPut(SEED_SUPPLIERS);
      }
      if ((await db.stockItems.count()) === 0) {
        await db.stockItems.bulkPut(SEED_STOCK_ITEMS);
      }
      if ((await db.stockMovements.count()) === 0) {
        await db.stockMovements.bulkPut(SEED_MOVEMENTS);
      }
      if ((await db.workOrders.count()) === 0) {
        await db.workOrders.bulkPut(SEED_WORK_ORDERS);
      }
      if ((await db.paymentRecords.count()) === 0) {
        await db.paymentRecords.bulkPut(SEED_PAYMENTS);
      }
      if ((await db.workshopUsers.count()) === 0) {
        await db.workshopUsers.bulkPut(
          SEED_USERS.map((u) => ({...u, passwordHash: defaultHash}))
        );
      }
    }
  );
}

export async function resetDatabaseToSeed(): Promise<void> {
  const defaultHash = await hashPassword(INITIAL_WORKSHOP_PASSWORD);

  await db.transaction(
    'rw',
    [
      db.workshopSettings,
      db.clients,
      db.vehicles,
      db.suppliers,
      db.stockItems,
      db.stockMovements,
      db.workOrders,
      db.paymentRecords,
      db.workshopUsers,
      db.syncQueue,
      db.syncMeta,
    ],
    async () => {
      await Promise.all([
        db.workshopSettings.clear(),
        db.clients.clear(),
        db.vehicles.clear(),
        db.suppliers.clear(),
        db.stockItems.clear(),
        db.stockMovements.clear(),
        db.workOrders.clear(),
        db.paymentRecords.clear(),
        db.workshopUsers.clear(),
        db.syncQueue.clear(),
        db.syncMeta.clear(),
      ]);
      await db.workshopSettings.put(DEFAULT_SETTINGS);
      await db.clients.bulkPut(SEED_CLIENTS);
      await db.vehicles.bulkPut(SEED_VEHICLES);
      await db.suppliers.bulkPut(SEED_SUPPLIERS);
      await db.stockItems.bulkPut(SEED_STOCK_ITEMS);
      await db.stockMovements.bulkPut(SEED_MOVEMENTS);
      await db.workOrders.bulkPut(SEED_WORK_ORDERS);
      await db.paymentRecords.bulkPut(SEED_PAYMENTS);
      await db.workshopUsers.bulkPut(
        SEED_USERS.map((u) => ({...u, passwordHash: defaultHash}))
      );
    }
  );
}
